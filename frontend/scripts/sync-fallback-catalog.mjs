#!/usr/bin/env node
/**
 * Regenerates src/lib/catalog.fallback.ts from the live /api/v1/catalog
 * response. Run this whenever the backend's prisma/data/catalog.ts changes
 * and you've re-seeded — keeps the bundled offline catalog in sync with
 * what users see online.
 *
 * Source of truth: bridgekitty-backend's prisma/data/catalog.ts.
 * This script mirrors that into the frontend bundle so that:
 *   1. First-ever visits with no localStorage cache and a slow / down
 *      backend still render a usable swap form.
 *   2. The fallback never silently drifts from prod — running this script
 *      once per backend catalog change is the discipline.
 *
 * Usage:
 *     npm run sync:fallback                     # uses prod URL
 *     CATALOG_URL=http://localhost:3000/api/v1/catalog npm run sync:fallback
 *
 * Writes src/lib/catalog.fallback.ts. Use `git diff` afterwards to review.
 */
import { writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const DEFAULT_URL = "https://api.bridgekitty.persistence.one/api/v1/catalog";
const url = process.env.CATALOG_URL ?? DEFAULT_URL;

const __dirname = dirname(fileURLToPath(import.meta.url));
const outPath = join(__dirname, "..", "src", "lib", "catalog.fallback.ts");

console.log(`[sync-fallback] fetching ${url}…`);
const res = await fetch(url);
if (!res.ok) {
  console.error(`[sync-fallback] fetch failed: ${res.status} ${res.statusText}`);
  process.exit(1);
}
const data = await res.json();
const chains = Array.isArray(data.chains) ? data.chains : [];
const tokensByChainKey = data.tokensByChainKey ?? {};
if (chains.length === 0) {
  console.error("[sync-fallback] /catalog returned no chains — refusing to write empty fallback.");
  process.exit(1);
}

// We strip backend-only fields (provider attribution, fetchedAt, etc.) and
// emit the minimal shape the frontend's Token / Chain types declare. Same
// shape that loadCatalog() expects from the live endpoint.
const chainsOut = chains.map((c) => ({
  key: c.key,
  chainId: c.chainId,
  name: c.name,
  logoURI: c.logoURI,
  blockExplorerUrl: c.blockExplorerUrl ?? null,
}));

const tokensOut = {};
for (const c of chains) {
  const list = tokensByChainKey[c.key] ?? [];
  tokensOut[c.key] = list.map((t) => ({
    symbol: t.symbol,
    name: t.name,
    address: t.address,
    decimals: t.decimals,
    logoURI: t.logoURI,
    tags: t.tags ?? [],
  }));
}

const totalTokens = Object.values(tokensOut).reduce((sum, list) => sum + list.length, 0);

const banner = `// AUTO-GENERATED by scripts/sync-fallback-catalog.mjs from
//   ${url}
// Generated at ${new Date().toISOString()}.
// Do NOT edit by hand — run \`npm run sync:fallback\` after backend
// catalog changes (bridgekitty-backend's prisma/data/catalog.ts).`;

const file = `${banner}
import type { Chain, Token } from './catalog';

/**
 * Minimal hardcoded catalog snapshot used only when:
 *   1. There is no cached snapshot in localStorage (first-ever visit), AND
 *   2. The fetch of /api/v1/catalog fails or times out.
 *
 * Mirrors what /api/v1/catalog returned at sync time. Updating this file
 * by hand will pass typecheck but get clobbered the next time anyone runs
 * \`npm run sync:fallback\`. Edit the upstream catalog instead:
 * bridgekitty-backend/prisma/data/catalog.ts.
 */
export const FALLBACK_CATALOG: { chains: Chain[]; tokensByChainKey: Record<string, Token[]> } = {
  chains: ${JSON.stringify(chainsOut, null, 2).replace(/\n/g, "\n  ")},
  tokensByChainKey: ${JSON.stringify(tokensOut, null, 2).replace(/\n/g, "\n  ")},
};
`;

writeFileSync(outPath, file, "utf8");
console.log(`[sync-fallback] wrote ${chainsOut.length} chains, ${totalTokens} tokens to ${outPath}`);
